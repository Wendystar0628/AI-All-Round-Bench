import puppeteer from 'puppeteer-core';
const browser = await puppeteer.connect({ browserURL: 'http://127.0.0.1:19106', defaultViewport: null });
const page = (await browser.pages()).find(p => p.url().includes('18106'));
page.on('pageerror', err => console.log('PAGEERROR', err.message));
await page.reload({ waitUntil: 'load' });
await new Promise(r => setTimeout(r, 700));
await page.evaluate(() => window.bench.reset());
await new Promise(r => setTimeout(r, 300));
const out = await page.evaluate(async () => {
  const os = window.__os;
  const child = os.createChild(os.root);
  await new Promise(r => setTimeout(r, 400));
  const w = await os.openApp(child, 'player');
  await new Promise(r => setTimeout(r, 600));
  w.app.setMode('rehearsal');
  w.app.startRehearsal();
  await new Promise(r => setTimeout(r, 5000));
  const live = { t: w.app.sim.state.t, alive: w.app.sim.state.alive, samples: w.app.recordSamples.length };
  w.app.saveRecord();
  const recs = (child.fs.list('/Documents') || []).filter(f => f.path.endsWith('.record'));
  const path = recs[0]?.path;
  w.app.loadRecord(path);
  await new Promise(r => setTimeout(r, 300));
  const loaded = { mode: w.app.mode, dur: w.app.record.duration, samples: w.app.record.samples.length, scene: w.app.scenePath };
  w.app.seek(2.5);
  await new Promise(r => setTimeout(r, 300));
  const at = { time: w.app.time, state: w.app.recordStateAt(2.5) };
  w.app.continueFromHere();
  await new Promise(r => setTimeout(r, 2000));
  const cont = { mode: w.app.mode, t: w.app.sim.state.t, alive: w.app.sim.state.alive, samples: w.app.recordSamples.length };
  return { live, path, recSize: child.fs.get(path)?.size, loaded, at: { time: at.time, t: at.state?.t, alive: at.state?.alive, pos: at.state?.pos }, cont };
});
console.log(JSON.stringify(out, null, 2));
await browser.disconnect();