import puppeteer from 'puppeteer-core';
const browser = await puppeteer.connect({ browserURL: 'http://127.0.0.1:19106', defaultViewport: null });
const page = (await browser.pages()).find(p => p.url().includes('18106'));
page.on('pageerror', err => console.log('PAGEERROR', err.message));
await page.reload({ waitUntil: 'load' });
await new Promise(r => setTimeout(r, 700));
await page.evaluate(() => window.bench.reset());
await new Promise(r => setTimeout(r, 300));
const out = await page.evaluate(async () => {
  const os = window.__os;
  const br = await os.openApp(os.root, 'browser');
  await new Promise(r => setTimeout(r, 400));
  const b = br.app;
  b.navigate('https://www.bilibili.com');
  await new Promise(r => setTimeout(r, 5000));
  const t1 = b.inspect(br);
  b.newTab('https://example.com');
  await new Promise(r => setTimeout(r, 3000));
  const t2 = b.inspect(br);
  b.activate(t1[0].tabId);
  await new Promise(r => setTimeout(r, 400));
  const active = b.active;
  b.closeTab(t2[0].tabId);
  await new Promise(r => setTimeout(r, 400));
  const t3 = b.inspect(br);
  return { t1, t2, active, t3, tabCount: b.tabs.length, title: br.title };
});
console.log(JSON.stringify(out, null, 2));
