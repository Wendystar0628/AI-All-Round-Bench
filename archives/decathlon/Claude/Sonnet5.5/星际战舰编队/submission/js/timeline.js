function shake(t, amp) {
  // 以整圈数的正弦叠加，循环处连续
  return [amp * (per(7, t, 0.3) * 0.6 + per(19, t, 1.0) * 0.3), amp * (per(9, t, 2.0) * 0.6 + per(23, t, 0.5) * 0.25), amp * (per(5, t, 4.0) * 0.5 + per(17, t, 2.0) * 0.3)];
}

function evalKeys(keys, t) {
  var n = keys.length;
  var ks = keys.map(function (k) { return { t: k.t, v: k.p.concat(k.g, [k.f]) }; });
  var v = splineEval(ks, t);
  return { p: v.slice(0, 3), g: v.slice(3, 6), f: v[6] };
}
var _KS_FLY = null, _KS_STRIKE = null;
function evalCached(keys, cacheName, t) {
  var c = cacheName === 'fly' ? _KS_FLY : _KS_STRIKE;
  if (!c) { c = keys.map(function (k) { return { t: k.t, v: k.p.concat(k.g, [k.f]) }; }); if (cacheName === 'fly') _KS_FLY = c; else _KS_STRIKE = c; }
  var v = splineEval(c, t);
  return { p: v.slice(0, 3), g: v.slice(3, 6), f: v[6] };
}

function cameraAt(t, aspect) {
  var shot = { scene: 'ext', post: {} };
  var e;
  if (t >= 62.4 || t < 24) {
    var u = t >= 62.4 ? t : t + TL.T;
    e = evalCached(CAM_FLY, 'fly', u);
    // 末尾拉升时的加速感：视场随推进增宽，随后回落
    var boost = boostf(t);
    e.f += 0.06 * boost;
    shot.scene = 'ext';
  } else if (t < 33) {
    shot.scene = 'core'; e = camCore(t);
  } else if (t < 39) {
    shot.scene = 'corridor'; e = camCorridor(t);
  } else if (t >= 57.2 && t < 58.8) {
    if (!_KS_PD) _KS_PD = CAM_PD.map(function (k) { return { t: k.t, v: k.p.concat(k.g, [k.f]) }; });
    var v = splineEval(_KS_PD, t); e = { p: v.slice(0, 3), g: v.slice(3, 6), f: v[6] };
    shot.scene = 'ext';
  } else {
    e = evalCached(CAM_STRIKE, 'strike', t);
    shot.scene = 'ext';
  }
  var sh = shake(t, shot.scene === 'ext' ? 0.5 : 0.25);
  shot.cam = { pos: [e.p[0] + sh[0], e.p[1] + sh[1], e.p[2] + sh[2]], target: [e.g[0] + sh[0] * 0.5, e.g[1] + sh[1] * 0.5, e.g[2] + sh[2] * 0.5], fov: e.f, near: 0.5, far: 80000, roll: 0.012 * per(6, t, 0.0) };
  if (e.roll) shot.cam.roll += e.roll;
  return shot;
}
