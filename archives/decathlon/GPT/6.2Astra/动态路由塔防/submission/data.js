function graph(m) {
  let g = {};
  function add(x, z) {
    let k = key(x, z);
    return (g[k] ??= { k, x, z, adj: [], road: true, old: m.old.some((a) => key(...a) == k) });
  }
  for (let line of m.lines) {
    let prev = add(...line[0]);
    for (let [x, z] of line.slice(1)) {
      while (prev.x != x || prev.z != z) {
        let nxt = add(prev.x + Math.sign(x - prev.x), prev.z + Math.sign(z - prev.z));
        if (!prev.adj.includes(nxt)) {
          prev.adj.push(nxt);
          nxt.adj.push(prev);
        }
        prev = nxt;
      }
    }
  }
  m.ins.forEach((v, i) => (g[key(...v)].entry = i + 1));
  m.outs.forEach((v, i) => (g[key(...v)].exit = i + 1));
  m.nodes.forEach((v, i) => (g[key(...v)].node = i + 1));
  return g;
}
