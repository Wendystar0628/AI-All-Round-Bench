/* ---------- 轮廓生成 ---------- */
function catmull(p0,p1,p2,p3,t){
  const t2=t*t,t3=t2*t;
  return 0.5*((2*p1)+(-p0+p2)*t+(2*p0-5*p1+4*p2-p3)*t2+(-p0+3*p1-3*p2+p3)*t3);
}
// 笔画采样：中心线 + 宽度
function sampleStroke(stroke,step){
  const p=stroke.p, n=p.length; const out=[];
  if(n===1){ out.push({x:p[0][0],y:p[0][1],w:p[0][2]}); return out; }
  const segs=n-1;
  for(let i=0;i<segs;i++){
    const a=p[Math.max(0,i-1)], b=p[i], c=p[i+1], d=p[Math.min(n-1,i+2)];
    const dist=Math.hypot(c[0]-b[0],c[1]-b[1]);
    const steps=clamp(Math.ceil(dist/(step||2.2)),3,48);
    for(let s=0;s<steps;s++){
      const t=s/steps;
      out.push({x:catmull(a[0],b[0],c[0],d[0],t), y:catmull(a[1],b[1],c[1],d[1],t),
        w:lerp(b[2],c[2],smooth(t))});
    }
  }
  const l=p[n-1]; out.push({x:l[0],y:l[1],w:l[2]});
  return out;
}
