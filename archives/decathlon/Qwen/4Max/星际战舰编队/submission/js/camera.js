SF.cameraAt = function (t) {
  const shots = SF.cam.shots;
  let s = shots[shots.length - 1];
  for (const sh of shots) if (t >= sh.t0 && t < sh.t1) { s = sh; break; }
  const pos = SF.track(s.keys.map(k => ({ t: k.t, v: k.p })), t);
  const look = SF.track(s.keys.map(k => ({ t: k.t, v: k.l })), t);
  const fov = SF.trackScalar(s.keys.map(k => ({ t: k.t, v: k.f })), t);
  const w = SF.TAU / SF.LOOP, amp = s.interior ? 0.55 : 1.4;
  pos[0] += Math.sin(w * t * 5 + 1.3) * amp;
  pos[1] += Math.sin(w * t * 7 + 4.1) * amp * 0.7;
  pos[2] += Math.cos(w * t * 6 + 2.2) * amp;
  look[0] += Math.sin(w * t * 4 + 0.7) * amp * 0.5;
  look[1] += Math.cos(w * t * 5 + 3.3) * amp * 0.4;
  const roll = Math.sin(w * t * 3 + 1) * 0.012 + (s.interior ? 0 : Math.sin(w * t * 2 + 2) * 0.01);
  return { pos, look, fov, roll, interior: s.interior, shot: s };
};

SF.wipeAt = function (t) {
  for (const tw of SF.cam.wipes) {
    const d = Math.abs(t - tw);
    if (d < 0.27) return 1 - SF.smooth(0.02, 0.27, d);
  }
  return 0;
};