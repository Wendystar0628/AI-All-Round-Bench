export function seedRootFS(vfs, presets) {
  const dirs = ['/System', '/System/Programs', '/System/Kernels', '/System/Snapshots', '/Demo', '/Documents', '/Desktop', '/下载', '/回收站'];
  for (const d of dirs) vfs.mkdir(d);
  for (const [p, c] of (presets ? presets.rootFiles : [])) vfs.write(p, c);
}

