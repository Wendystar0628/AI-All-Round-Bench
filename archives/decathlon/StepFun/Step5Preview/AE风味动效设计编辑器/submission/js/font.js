const cache={};
APP.font={
  has:ch=>!!G[ch],
  advance:ch=>{const g=G[ch];return g?g[0]:1000;},
  /* 字形轮廓(已并集), 带缓存; 返回 {adv, contours, tris} */
  glyph(ch){
    if(cache[ch])return cache[ch];
    const gc=glyphContours(ch);
    if(!gc){cache[ch]={adv:1000,contours:[],tris:null};return cache[ch];}
    let contours=gc.contours;
    if(contours.length>1){
      const u=APP.geom.unionContours(contours);
      contours=u&&u.length?u:contours;
    }
    const g={adv:gc.adv,contours};
    g.bounds=contourBounds(contours);
    cache[ch]=g;
    return g;
  },
  /* 三角化字形(用于挤出/变形) */
  mesh(ch){
    const g=APP.font.glyph(ch);
    if(g.tris!==undefined&&g.tris!==null)return g.tris;
    const t=APP.geom.triangulate(g.contours);
    g.tris=t;return t;
  },
  /* 已支持的字符 */
  chars(){
    const cjk=[],lat=[];
    for(const k in G){if(!G[k])continue;
      const c=k.charCodeAt(0);
      if(c>0x2E80)cjk.push(k);else lat.push(k);}
    return {cjk:cjk.sort(),lat:lat.sort()};
  },
  glyphs:G
};
function contourBounds(cs){
  let x0=1e9,y0=1e9,x1=-1e9,y1=-1e9;
  for(const c of cs)for(const p of c){x0=Math.min(x0,p.x);y0=Math.min(y0,p.y);x1=Math.max(x1,p.x);y1=Math.max(y1,p.y);}
  if(x0>x1)return {x:0,y:0,w:0,h:0};
  return {x:x0,y:y0,w:x1-x0,h:y1-y0};
}
