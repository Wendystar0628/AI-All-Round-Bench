function sampleStroke(st){
  const p=st.p, out=[]; let cx=0,cy=0;
  for(let i=0;i<p.length;){
    if(p[i]==='q'){
      const qx=p[i+1],qy=p[i+2],ex=p[i+3],ey=p[i+4];
      const N=12;
      for(let k=1;k<=N;k++){const s=k/N,mt=1-s;
        out.push({x:mt*mt*cx+2*mt*s*qx+s*s*ex, y:mt*mt*cy+2*mt*s*qy+s*s*ey});}
      cx=ex;cy=ey;i+=5;
    }else{
      const ex=p[i],ey=p[i+1], d=Math.hypot(ex-cx,ey-cy), N=Math.max(1,Math.ceil(d/36));
      for(let k=1;k<=N;k++)out.push({x:cx+(ex-cx)*k/N, y:cy+(ey-cy)*k/N});
      cx=ex;cy=ey;i+=2;
    }
  }
  return out;
}
function offsetContour(pts,widths,cap){
  // 返回闭合轮廓 [{x,y}...] (逆时针, y向下)
  const n=pts.length;
  const L=[],R=[];
  for(let i=0;i<n;i++){
    const p=pts[i];
    let tx,ty;
    if(i===0){tx=pts[1].x-p.x;ty=pts[1].y-p.y;}
    else if(i===n-1){tx=p.x-pts[i-1].x;ty=p.y-pts[i-1].y;}
    else {tx=pts[i+1].x-pts[i-1].x;ty=pts[i+1].y-pts[i-1].y;}
    const l=Math.hypot(tx,ty)||1; tx/=l;ty/=l;
    const h=widths[i]/2;
    L.push({x:p.x-ty*h, y:p.y+tx*h});
    R.push({x:p.x+ty*h, y:p.y-tx*h});
  }
  const addArc=(c,from,to)=>{
    const a0=Math.atan2(from.y-c.y,from.x-c.x), a1=Math.atan2(to.y-c.y,to.x-c.x);
    let da=a1-a0; while(da>Math.PI)da-=2*Math.PI; while(da<-Math.PI)da+=2*Math.PI;
    const steps=Math.max(2,Math.ceil(Math.abs(da)/0.35));
    for(let k=1;k<steps;k++){const a=a0+da*k/steps;const r=Math.hypot(from.x-c.x,from.y-c.y);
      out.push({x:c.x+Math.cos(a)*r,y:c.y+Math.sin(a)*r});}
  };
  const out=[];
  // 左侧正走 + 斜接
  for(let i=0;i<n;i++){
    if(i>0){
      const a=L[i-1],b=L[i],c=L[Math.min(i+1,n-1)];
      const d1={x:b.x-a.x,y:b.y-a.y},d2={x:c.x-b.x,y:c.y-b.y};
      const cross=d1.x*d2.y-d1.y*d2.x;
      if(cross<-1e-6){ // 外角: 加斜接点
        const t=((a.x-b.x)*d2.y-(a.y-b.y)*d2.x)/(d1.x*d2.y-d1.y*d2.x);
        const mx=a.x+d1.x*t, my=a.y+d1.y*t;
        if(Math.hypot(mx-b.x,my-b.y)<widths[i]*1.6){ out.push({x:mx,y:my}); }
      }
    }
    out.push(L[i]);
  }
  if(cap!=='f'){
    addArc(pts[n-1],L[n-1],R[n-1]);
  }
  for(let i=n-1;i>=0;i--){
    if(i<n-1){
      const a=R[i+1],b=R[i],c=R[Math.max(i-1,0)];
      const d1={x:b.x-a.x,y:b.y-a.y},d2={x:c.x-b.x,y:c.y-b.y};
      const cross=d1.x*d2.y-d1.y*d2.x;
      if(cross>1e-6){
        const t=((a.x-b.x)*d2.y-(a.y-b.y)*d2.x)/(d1.x*d2.y-d1.y*d2.x);
        const mx=a.x+d1.x*t,my=a.y+d1.y*t;
        if(Math.hypot(mx-b.x,my-b.y)<widths[i]*1.6){ out.push({x:mx,y:my}); }
      }
    }
    out.push(R[i]);
  }
  if(cap!=='f'){ addArc(pts[0],R[0],L[0]); }
  // 统一为顺时针(y向下: 面积>0)
  let area=0;
  for(let i=0;i<out.length;i++){const a=out[i],b=out[(i+1)%out.length];area+=(b.x-a.x)*(b.y+a.y)/2;}
  if(area<0)out.reverse();
  return out;
}
function glyphContours(ch){
  const g=G[ch]; if(!g)return null;
  const adv=g[0], strokes=g[1], contours=[];
  for(const st of strokes){
    const w=st[0],cap=st[1],p=st[2];
    const pts=sampleStroke({p});
    if(pts.length<2)continue;
    let total=0;const seg=[];
    for(let i=1;i<pts.length;i++){const d=Math.hypot(pts[i].x-pts[i-1].x,pts[i].y-pts[i-1].y);seg.push(d);total+=d;}
    let w0,w1;
    if(Array.isArray(w)){w0=w[0];w1=w[1];}else{w0=w;w1=w;}
    const widths=[];let acc=0;
    for(let i=0;i<pts.length;i++){
      if(i>0)acc+=seg[i-1];
      widths.push(C.lerp(w0,w1,total>0?acc/total:0));
    }
    if(pts.length===1)pts.push({x:pts[0].x+0.01,y:pts[0].y});
    contours.push(offsetContour(pts,widths,cap||'f'));
  }
  return {adv,contours};
}

