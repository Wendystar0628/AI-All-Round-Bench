# Build assets/data.js: character images (trimmed, alpha-normalised, + baked white-outline sticker
# versions) as WebP data URIs, plus a 50 Hz RMS envelope of the track. (dev only)
import numpy as np, os, io, base64, json
from PIL import Image
from scipy.ndimage import distance_transform_edt, gaussian_filter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, '素材', '角色立绘')
OUT = os.path.join(ROOT, 'assets', 'data.js')
NAMES = ['tomori', 'anon', 'rana', 'soyo', 'taki']
PAD = 28  # room for sticker outline
OUTLINE = 15


def webp_uri(im, q=88):
    b = io.BytesIO()
    im.save(b, 'WEBP', quality=q, method=6)
    return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode('ascii'), len(b.getvalue())


data = {'img': {}, 'meta': {}}
total = 0
for n in NAMES:
    im = Image.open(os.path.join(SRC, n + '.png')).convert('RGBA')
    a = np.array(im).astype(np.float32)
    al = a[..., 3]
    # normalise near-opaque alpha to fully opaque; keep soft edge
    al = np.clip(al * (255.0 / 246.0), 0, 255)
    al[al < 6] = 0
    a[..., 3] = al
    # clear colour in fully transparent pixels (avoid halo bleed when resampling)
    a[al == 0, :3] = 0
    im2 = Image.fromarray(a.astype(np.uint8), 'RGBA')
    bb = im2.getbbox()
    x0, y0, x1, y1 = bb
    x0 = max(0, x0 - PAD); y0 = max(0, y0 - PAD)
    W, H = im2.size
    crop = Image.new('RGBA', (x1 - x0 + 2 * PAD, y1 - y0 + 2 * PAD), (0, 0, 0, 0))
    crop.paste(im2.crop((x0, y0, min(W, x1 + PAD), min(H, y1 + PAD))), (PAD - (bb[0] - x0) + (bb[0] - x0), PAD - (bb[1] - y0) + (bb[1] - y0)))
    # simpler: rebuild exact padded crop
    crop = Image.new('RGBA', (x1 - bb[0] + 2 * PAD, y1 - bb[1] + 2 * PAD), (0, 0, 0, 0))
    crop.paste(im2.crop(bb), (PAD, PAD))
    uri, sz = webp_uri(crop, 90)
    total += sz
    # sticker: white outline from distance transform of alpha
    ca = np.array(crop)[..., 3].astype(np.float32) / 255.0
    inside = ca > 0.35
    dist = distance_transform_edt(~inside)
    ol = np.clip(OUTLINE + 0.8 - dist, 0, 1)  # anti-aliased edge
    # smooth the outline shape a bit (rounder sticker silhouette)
    ol = np.clip(gaussian_filter(ol, 1.2) * 1.15, 0, 1)
    st = np.zeros((crop.size[1], crop.size[0], 4), np.float32)
    st[..., :3] = 255
    st[..., 3] = ol * 255
    base = Image.fromarray(st.astype(np.uint8), 'RGBA')
    base.alpha_composite(crop)
    suri, ssz = webp_uri(base, 90)
    total += ssz
    data['img'][n] = uri
    data['img'][n + '_st'] = suri
    data['meta'][n] = {'w': crop.size[0], 'h': crop.size[1], 'ox': bb[0] - PAD, 'oy': bb[1] - PAD}
    print(n, crop.size, 'webp', sz // 1024, 'KB  sticker', ssz // 1024, 'KB')

# RMS envelope 50 Hz, normalised 0..1 (sqrt-compressed), stored as 0..255 ints
rms = np.load(os.path.join(ROOT, '_dev', 'out', 'rms100.npy'))
r50 = rms[: len(rms) // 2 * 2].reshape(-1, 2).mean(1)
r50 = r50 / np.percentile(r50, 99.5)
r50 = np.clip(r50, 0, 1)
data['rms50'] = [int(round(v * 255)) for v in r50]
print('rms frames', len(r50), 'total img KB', total // 1024)

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('/* generated by _dev/build_assets.py: images derived from 素材/角色立绘, RMS envelope of the track */\n')
    f.write('window.PV_DATA = ')
    json.dump(data, f, separators=(',', ':'))
    f.write(';\n')
print('wrote', OUT, os.path.getsize(OUT) // 1024, 'KB')
