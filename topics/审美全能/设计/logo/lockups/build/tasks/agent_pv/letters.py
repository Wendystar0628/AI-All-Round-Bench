"""01 现代Agent概念PV · 笔画处理（字体单位，1000 em，y 朝上）。

方言「光标宋」：思源宋体 Heavy 的高反差骨架、横末三角、撇捺钩的弧都照宋体留着（人写的那一面不动），
四个汉字统一改两样“落点”——
  1. 方点  所有的点都换成一块立着的方块：终端里光标的形状（呼应）；
  2. 方脚  收笔朝下、末端空着的竖，宋体的斜脚补成平底，方方正正落在格上（精确）。
高潮：「代」——代理、代劳，替人去做——弋上那一点就是光标：全件唯一亮着的那一块，比别的方点大一号、高一截
（形在这里；亮、闪和落在它上面的星在 layers.py、__init__.py 和入场里）。
拉丁字母 Agent、PV 是 Didone（english.py）。
"""
from lockupkit.geom import union, diff, rect, poly
from lockupkit.strokes import Title
from lockupkit import paths
from .strokes import STROKES

FONT = paths.SONG_HEAVY
TEXT = '现代概念'
HAIR = 28            # 本题字的最细笔画：横（字体单位）

# 每个点的方块：中心（落在原来那一点的圆头上）、宽、高（字体单位）。「代5」是光标
DOTS = {
    '代5': (806, 754, 162, 236),
    '概4': (297, 420, 64, 96),
    '概9': (556, 204, 92, 130),
    '念3': (488, 556, 92, 130),
    '念5': (134, 112, 92, 130),
    '念7': (506, 205, 92, 130),
    '念8': (838, 130, 92, 130),
}

# 和别的笔画连在一起的点（不是独立轮廓）：照原来那一点的轮廓描一圈擦掉（只擦点，不碰相连的那一笔），再放方块
ERASE = {
    '概4': [(257.5, 330), (335.5, 330), (335.5, 525), (257.5, 525)],                       # 木的点：夹在两根竖之间
    '概9': [(484, 318), (712, 318), (700, 270), (690, 240), (680, 210), (668, 180), (655, 150),
            (641, 120), (626, 92), (528, 92), (527, 171), (518, 218), (488, 250)],          # 皀的点：留着提的尖
    '念3': [(410, 598), (410, 644), (582, 644), (582, 468), (412, 468)],                   # 今的点：头挂在人的撇下
    '念7': [(404, 332), (420, 330), (528, 300), (578, 262), (610, 240), (610, 116), (440, 116),
            (410, 150), (410, 262), (436, 282), (436, 292), (404, 297)],                    # 心的中点：头压在卧钩上、肩上接撇
}

# 方脚：每一笔竖的收笔（宋体的斜脚）补成方的——左右边、平底的高度（字体单位，量自坐标底图）
FEET = {
    '现5': (423, 554, 224),     # 见的左竖
    '现6': (787, 925, 236),     # 见的横折
    '代2': (162, 304, -95),     # 亻的竖
    '概2': (132, 257, -95),     # 木的竖
    '概6': (496, 605, 327),     # 皀的横折
}


def block(sid):
    cx, cy, w, h = DOTS[sid]
    return rect(cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2)


def square_foot(path, s):
    """收笔朝下的竖：宋体的斜脚补成平底的方脚，平底落在原来最低的那一点上。"""
    x0, x1, y = FEET[s.id]
    return union(path, rect(x0, y, x1, y + 0.6 * s.w_end))


def letters(cursor=True):
    """返回排版前的 Title（每个字的手术都挂好了；小形态也用这一份，方点、方脚小了也认得）。
    cursor=False 时「代」的光标不并进字形（光标单独一层，换料、亮、闪）；它的形记在 T['代'].cursor，中心在 anchors['cursor']。"""
    T = Title(FONT, TEXT, STROKES)
    # ---- 高潮：「代」的点 → 光标
    s = T.s('代5')
    cur = block('代5')
    cx, cy, cw, ch = DOTS['代5']
    T['代'].cursor = cur
    T['代'].anchors['cursor'] = (cx, cy)
    T['代'].anchors['cursor_tr'] = (cx + cw / 2, cy + ch / 2)
    s.variant(cur if cursor else None)
    # ---- 呼应：其余的点 → 方块（独立轮廓的点整个换掉；连着别的笔画的点照轮廓擦掉再放）
    for st in T.q(type='点').exclude('代5'):
        if st.id in ERASE:
            st.op(lambda p, s_, e=ERASE[st.id], b=block(st.id): union(diff(p, poly(e)), b))
        else:
            st.variant(block(st.id))
    # ---- 方言：方脚
    T.sel(*FEET).op(square_foot)
    return T
